#!/usr/bin/env python3
"""Generates the client themes from the design tokens (P-42, docs/client/ARCHITECTURE.md §8).

    brand/design-system/tokens.json
        -> web/src/shared/theme/tokens.css          CSS custom properties, light and dark ([data-theme])
        -> mobile/lib/shared/theme/tokens.g.dart    Dart constants (PwColorTokens.light/dark, PwSpacing, PwRadius, ...)

    python3 scripts/build_tokens.py            # write both files
    python3 scripts/build_tokens.py --check    # exit 1 if a generated file is missing or out of date (CI)

Every value is parsed strictly: an unknown colour, length or shadow format stops the build instead of producing a
theme that silently differs from the design system. Standard library only.
"""
import argparse
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "brand" / "design-system" / "tokens.json"
WEB_OUT = ROOT / "web" / "src" / "shared" / "theme" / "tokens.css"
MOBILE_OUT = ROOT / "mobile" / "lib" / "shared" / "theme" / "tokens.g.dart"
HEADER = "generated by scripts/build_tokens.py from brand/design-system/tokens.json; do not edit"


class TokenError(ValueError):
    pass


# ---------- parsing ----------

def parse_color(value: str):
    """'#rgb', '#rrggbb', '#rrggbbaa' or 'rgba(r, g, b, a)' -> (r, g, b, alpha 0..1)."""
    value = value.strip()
    m = re.fullmatch(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})", value)
    if m:
        h = m.group(1)
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        alpha = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), alpha
    m = re.fullmatch(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)", value)
    if m:
        r, g, b = (int(m.group(i)) for i in (1, 2, 3))
        if max(r, g, b) > 255:
            raise TokenError(f"colour channel out of range: {value}")
        return r, g, b, float(m.group(4)) if m.group(4) is not None else 1.0
    raise TokenError(f"unsupported colour: {value!r}")


def parse_px(value) -> float:
    """'16px' or a number -> 16.0."""
    if isinstance(value, (int, float)):
        return float(value)
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)px", str(value).strip())
    if not m:
        raise TokenError(f"expected a px length: {value!r}")
    return float(m.group(1))


def parse_letter_spacing(value, font_size: float) -> float:
    """'0.04em' or '1px' -> logical pixels (Flutter has no em)."""
    text = str(value).strip()
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)em", text)
    if m:
        return float(m.group(1)) * font_size
    return parse_px(text)


def parse_shadow(value: str):
    """'0 12px 32px rgba(...)' -> (x, y, blur, spread, colour). One shadow layer, not inset."""
    m = re.fullmatch(r"(-?\d+(?:px)?)\s+(-?\d+(?:px)?)\s+(\d+(?:px)?)(?:\s+(-?\d+(?:px)?))?\s+(.+)", value.strip())
    if not m or "inset" in value:
        raise TokenError(f"unsupported shadow: {value!r}")
    x, y, blur = (parse_px(m.group(i) if m.group(i).endswith("px") else m.group(i) + "px") for i in (1, 2, 3))
    spread = parse_px(m.group(4) if m.group(4).endswith("px") else m.group(4) + "px") if m.group(4) else 0.0
    return x, y, blur, spread, parse_color(m.group(5))


def parse_linear_gradient(value: str):
    """'linear-gradient(165deg, #a 0%, #b 100%)' -> (angle degrees, [(colour, stop 0..1)])."""
    m = re.fullmatch(r"linear-gradient\(\s*(-?\d+(?:\.\d+)?)deg\s*,(.+)\)", value.strip())
    if not m:
        raise TokenError(f"unsupported gradient: {value!r}")
    stops = []
    for part in m.group(2).split(","):
        sm = re.fullmatch(r"\s*(#[0-9a-fA-F]{3,8})\s+(\d+(?:\.\d+)?)%\s*", part)
        if not sm:
            raise TokenError(f"unsupported gradient stop {part!r} in {value!r}")
        stops.append((parse_color(sm.group(1)), float(sm.group(2)) / 100))
    if len(stops) < 2:
        raise TokenError(f"a gradient needs two stops: {value!r}")
    return float(m.group(1)), stops


def theme_values(token, themes):
    """Per-theme values of a colour/shadow token; a missing theme inherits the first (design system rule)."""
    value = token["value"]
    if isinstance(value, str):
        return {theme: value for theme in themes}
    first = value.get(themes[0])
    if first is None:
        raise TokenError(f"token {token['name']} has no value for the first theme {themes[0]}")
    return {theme: value.get(theme, first) for theme in themes}


def load(path: Path = TOKENS) -> dict:
    tokens = json.loads(path.read_text(encoding="utf-8"))
    themes = [t["id"] for t in tokens["color"]["themes"]]
    if themes[:2] != ["light", "dark"]:
        raise TokenError(f"expected themes light and dark first, got {themes}")
    names = set()
    for family in ("color", "spacing", "radius", "shadow", "gradient"):
        for token in tokens.get(family, {}).get("tokens", []):
            if not re.fullmatch(r"[a-z][a-z0-9-]*", token["name"]):
                raise TokenError(f"token name must be kebab-case: {token['name']!r}")
            if token["name"] in names:
                raise TokenError(f"duplicate token name: {token['name']}")
            names.add(token["name"])
    return tokens


# ---------- naming ----------

def camel(name: str) -> str:
    """'surface-raised' -> 'surfaceRaised', 'map-route-1' -> 'mapRoute1'."""
    head, *rest = name.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def fmt_num(x: float) -> str:
    return str(int(x)) if float(x).is_integer() else f"{x:.4f}".rstrip("0").rstrip(".")


# ---------- web ----------

def build_css(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    colors = tokens["color"]["tokens"]
    shadows = tokens.get("shadow", {}).get("tokens", [])
    lines = [f"/* {HEADER}. */", ""]
    for i, theme in enumerate(themes):
        selector = f':root, [data-theme="{theme}"]' if i == 0 else f'[data-theme="{theme}"]'
        lines.append(f"{selector} {{")
        lines.append(f"  color-scheme: {theme if theme in ('light', 'dark') else 'normal'};")
        for token in colors:
            value = theme_values(token, themes)[theme]
            parse_color(value)
            lines.append(f"  --{token['name']}: {value.lower() if value.startswith('#') else value};")
        for token in shadows:
            value = theme_values(token, themes)[theme]
            parse_shadow(value)
            lines.append(f"  --{token['name']}: {value};")
        lines.append("}")
        lines.append("")
    lines.append(":root {")
    for family in ("spacing", "radius"):
        for token in tokens.get(family, {}).get("tokens", []):
            lines.append(f"  --{token['name']}: {fmt_num(parse_px(token['value']))}px;")
    for token in tokens.get("gradient", {}).get("tokens", []):
        parse_linear_gradient(token["value"])
        lines.append(f"  --{token['name']}: {token['value']};")
    for key, stack in tokens["type"]["families"].items():
        lines.append(f"  --font-{key}: {stack};")
    lines.append("}")
    for group in tokens["type"]["groups"]:
        family = group.get("family", "sans")
        for style in group["styles"]:
            size = parse_px(style["fontSize"])
            lines.append("")
            lines.append(f".pw-type-{style['name']} {{")
            lines.append(f"  font-family: var(--font-{style.get('family', family)});")
            lines.append(f"  font-size: {fmt_num(size)}px;")
            lines.append(f"  line-height: {fmt_num(parse_px(style['lineHeight']))}px;")
            lines.append(f"  font-weight: {int(style['fontWeight'])};")
            if style.get("letterSpacing"):
                lines.append(f"  letter-spacing: {style['letterSpacing']};")
            if style["name"] == "label":
                lines.append("  text-transform: uppercase;")
            lines.append("}")
    return "\n".join(lines) + "\n"


# ---------- mobile ----------

def dart_color(rgba) -> str:
    r, g, b, a = rgba
    return f"Color(0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X})"


def dart_shadow(value: str) -> str:
    x, y, blur, spread, color = parse_shadow(value)
    spread_part = f", spreadRadius: {fmt_num(spread)}" if spread else ""
    return f"[BoxShadow(offset: Offset({fmt_num(x)}, {fmt_num(y)}), blurRadius: {fmt_num(blur)}{spread_part}, color: {dart_color(color)})]"


def dart_gradient(value: str) -> str:
    angle, stops = parse_linear_gradient(value)
    # CSS: 0deg points up, angles turn clockwise. Alignment(x, y) has y pointing down.
    rad = math.radians(angle)
    ex, ey = round(math.sin(rad), 4), round(-math.cos(rad), 4)
    colors = ", ".join(dart_color(c) for c, _ in stops)
    positions = ", ".join(fmt_num(round(s, 4)) for _, s in stops)
    return (f"LinearGradient(begin: Alignment({fmt_num(-ex)}, {fmt_num(-ey)}), end: Alignment({fmt_num(ex)}, {fmt_num(ey)}), "
            f"colors: [{colors}], stops: [{positions}])")


def first_family(stack: str) -> str:
    return stack.split(",")[0].strip().strip('"').strip("'")


def build_dart(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    colors = tokens["color"]["tokens"]
    shadows = tokens.get("shadow", {}).get("tokens", [])
    fields = [camel(t["name"]) for t in colors] + [camel(t["name"]) for t in shadows]
    out = [f"// {HEADER}.", "// ignore_for_file: lines_longer_than_80_chars", "// dart format off", "",
           "import 'package:flutter/painting.dart';", "",
           "/// Colours and shadows of one theme. Use [PwColorTokens.light] or [PwColorTokens.dark].",
           "class PwColorTokens {", "  const PwColorTokens({"]
    out += [f"    required this.{f}," for f in fields]
    out += ["  });", ""]
    for token in colors:
        if token.get("usage"):
            out.append(f"  /// {token['usage'].splitlines()[0]}")
        out.append(f"  final Color {camel(token['name'])};")
    for token in shadows:
        if token.get("usage"):
            out.append(f"  /// {token['usage'].splitlines()[0]}")
        out.append(f"  final List<BoxShadow> {camel(token['name'])};")
    for theme in themes[:2]:
        out += ["", f"  static const {theme} = PwColorTokens("]
        for token in colors:
            out.append(f"    {camel(token['name'])}: {dart_color(parse_color(theme_values(token, themes)[theme]))},")
        for token in shadows:
            out.append(f"    {camel(token['name'])}: {dart_shadow(theme_values(token, themes)[theme])},")
        out.append("  );")
    out.append("}")
    for family, cls in (("spacing", "PwSpacing"), ("radius", "PwRadius")):
        out += ["", f"abstract final class {cls} {{"]
        for token in tokens.get(family, {}).get("tokens", []):
            out.append(f"  static const double {camel(token['name'])} = {fmt_num(parse_px(token['value']))};")
        out.append("}")
    out += ["", "abstract final class PwGradients {"]
    for token in tokens.get("gradient", {}).get("tokens", []):
        out.append(f"  static const {camel(token['name'])} = {dart_gradient(token['value'])};")
    out.append("}")
    families = tokens["type"]["families"]
    out += ["", "abstract final class PwTypeStyles {"]
    for group in tokens["type"]["groups"]:
        for style in group["styles"]:
            size = parse_px(style["fontSize"])
            height = parse_px(style["lineHeight"]) / size
            family = first_family(families[style.get("family", group.get("family", "sans"))])
            parts = [f"fontFamily: '{family}'", f"fontSize: {fmt_num(size)}", f"height: {fmt_num(round(height, 4))}",
                     f"fontWeight: FontWeight.w{int(style['fontWeight'])}"]
            if style.get("letterSpacing"):
                parts.append(f"letterSpacing: {fmt_num(round(parse_letter_spacing(style['letterSpacing'], size), 4))}")
            out.append(f"  static const {camel(style['name'])} = TextStyle({', '.join(parts)});")
    out.append("}")
    return "\n".join(out) + "\n"


# ---------- entry point ----------

def outputs(tokens: dict, web_out: Path, mobile_out: Path):
    return [(web_out, build_css(tokens)), (mobile_out, build_dart(tokens))]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated file is missing or out of date")
    parser.add_argument("--tokens", type=Path, default=TOKENS)
    parser.add_argument("--web-out", type=Path, default=WEB_OUT)
    parser.add_argument("--mobile-out", type=Path, default=MOBILE_OUT)
    parser.add_argument("--only", choices=["web", "mobile"], help="generate or check one client only")
    args = parser.parse_args(argv)
    try:
        files = outputs(load(args.tokens), args.web_out, args.mobile_out)
    except (TokenError, KeyError, json.JSONDecodeError) as error:
        print(f"tokens.json: {error}", file=sys.stderr)
        return 1
    if args.only:
        files = [files[0]] if args.only == "web" else [files[1]]
    stale = []
    for path, content in files:
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path}")
    if stale:
        for path in stale:
            print(f"{path} is out of date with brand/design-system/tokens.json. Run python3 scripts/build_tokens.py.",
                  file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
