#!/usr/bin/env python3
"""Keeps api/openapi.json, the machine-readable contract clients generate code from (P-41), in step with the backend.

The backend writes the document it serves to be/target/openapi.json when ApiSpecContractIntegrationTest runs. This
script normalizes it so the snapshot diffs cleanly and is the same on every machine: the environment-specific
`servers` entry is dropped, object keys are sorted, indentation is fixed.

    python3 scripts/openapi_snapshot.py write   # be/target/openapi.json -> api/openapi.json
    python3 scripts/openapi_snapshot.py check   # exit 1 if api/openapi.json is not the normalized generated document

Usually run through scripts/sync_openapi.sh, which runs the test first. Standard library only.
"""
import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = ROOT / "be" / "target" / "openapi.json"
SNAPSHOT = ROOT / "api" / "openapi.json"
FIX_HINT = "Run scripts/sync_openapi.sh and commit api/openapi.json together with the API change."


def normalize(text: str) -> str:
    """The canonical form of an OpenAPI document: no `servers`, sorted keys, two-space indent, final newline."""
    document = json.loads(text)
    if not isinstance(document, dict) or "openapi" not in document:
        raise ValueError("not an OpenAPI document")
    document.pop("servers", None)
    return json.dumps(document, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def write(generated: Path, snapshot: Path) -> int:
    if not generated.is_file():
        print(f"{generated} not found. Run ApiSpecContractIntegrationTest first (scripts/sync_openapi.sh does).", file=sys.stderr)
        return 1
    content = normalize(generated.read_text(encoding="utf-8"))
    snapshot.parent.mkdir(parents=True, exist_ok=True)
    changed = not snapshot.is_file() or snapshot.read_text(encoding="utf-8") != content
    snapshot.write_text(content, encoding="utf-8")
    print(f"{snapshot.relative_to(ROOT) if snapshot.is_relative_to(ROOT) else snapshot}: {'updated' if changed else 'unchanged'}")
    return 0


def check(generated: Path, snapshot: Path) -> int:
    if not generated.is_file():
        print(f"{generated} not found: the backend tests did not write the OpenAPI document.", file=sys.stderr)
        return 1
    if not snapshot.is_file():
        print(f"{snapshot} is missing. {FIX_HINT}", file=sys.stderr)
        return 1
    expected = normalize(generated.read_text(encoding="utf-8"))
    actual = snapshot.read_text(encoding="utf-8")
    if actual == expected:
        print("api/openapi.json matches the backend.")
        return 0
    diff = list(difflib.unified_diff(actual.splitlines(), expected.splitlines(),
                                     "api/openapi.json (committed)", "generated by the backend", lineterm=""))
    print(f"api/openapi.json is out of date with the backend. {FIX_HINT}", file=sys.stderr)
    print("\n".join(diff[:80]), file=sys.stderr)
    if len(diff) > 80:
        print(f"... {len(diff) - 80} more diff lines", file=sys.stderr)
    return 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["write", "check"])
    parser.add_argument("--generated", type=Path, default=GENERATED, help="document written by the backend tests")
    parser.add_argument("--snapshot", type=Path, default=SNAPSHOT, help="committed snapshot")
    args = parser.parse_args(argv)
    return write(args.generated, args.snapshot) if args.command == "write" else check(args.generated, args.snapshot)


if __name__ == "__main__":
    sys.exit(main())
